"""Pad-level chip_top sensor-I2C smoke test using project Python sensor models.

This test is for the real chip_top pad path, not the SIM-only sensor bus.
The Makefile target compiles chip_top RTL with CHIP_TOP_PAD_I2C=1, which keeps
`SIM` undefined so `src/i2c_master.sv` drives the physical sensor I2C pads:

    bidir_PAD[23] -> sensor SCL
    bidir_PAD[24] -> sensor SDA

The testbench wrapper exposes those pad nets as `sensor_scl_sample` and
`sensor_sda_sample`. This cocotb test attaches two open-drain I2C slave models
to the SDA pad via cocotbext-i2c-style `sda_o` signals:

    LIS2DW12 accelerometer at 7-bit address 0x19
    ADPD144RI PPG sensor at 7-bit address 0x64

The sensor payloads are generated by the repository's Python sensor models
(`scripts/sensor_models/sensors/accelerometer.py` and `ppg.py`) from small,
deterministic synthetic raw inputs. That means the test exercises:

    Python sensor model -> I2C register model -> chip_top pads ->
    GF180 IO model -> top/i2c_master -> accel_reader/ppg_fifo_reader

Pass criteria:
    * sensor SCL toggles on bidir_PAD[23]
    * the accelerometer init writes are observed over pads
    * at least one accelerometer data burst is read over pads
    * the PPG FIFO access-enable write is observed over pads
    * at least one PPG FIFO burst is read over pads
    * the internal accel_reader emits accel_valid_w
    * the internal ppg_fifo_reader emits ppg_sample_valid_w

This intentionally does not prove full feature correctness or ML/logit behavior.
It proves that real chip_top sensor-pad I2C traffic can reach sensor-like models
and return model-generated accel/PPG samples into the RTL.

Useful debug output:
    * the first decoded I2C address bytes seen on the pads
    * sensor-model transaction counters and last samples served
    * optional internal top/i2c_master/reader signals, when visible

Set I2C_PAD_VERBOSE=1 to print periodic snapshots while the test is running.
"""

