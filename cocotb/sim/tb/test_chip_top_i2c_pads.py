class PulseMonitor:
    """Edge-triggered monitor for one-cycle RTL pulses."""

    def __init__(self, handle, sample_fn=None):
        self.handle = handle
        self.sample_fn = sample_fn
        self.count = 0
        self.samples = []

    async def run(self):
        if self.handle is None:
            return
        while True:
            await RisingEdge(self.handle)
            await ReadOnly()
            self.count += 1
            if self.sample_fn is not None:
                self.samples.append(self.sample_fn())


class RegisterSensorDevice(I2cDevice):
    """Base class for simple register-addressed I2C sensor devices.

    It subclasses cocotbext-i2c so the device owns/release-drives SDA through
    the same open-drain style interface as cocotbext. The byte sampler is kept
    tolerant of this chip_top pad simulation's edge ordering; the stock
    cocotbext state machine was seeing false stop/repeated-start tokens while
    the passive monitor still decoded valid address bytes.
    """

    def __init__(self, *args, addr, **kwargs):
        self.addr = addr
        self.reg_ptr = 0
        self._first_write = True
        self._read_buf = []
        self.transactions = 0
        self.writes = 0
        self.reads = 0
        self.seen = False
        self.observed_tokens = []
        self._pending_start = False
        super().__init__(*args, **kwargs)

    def _scl_is_high(self):
        return str(self.scl.value) == "1"

    def _sda_is_high(self):
        return str(self.sda.value) == "1"

    async def _wait_start(self):
        if self._pending_start:
            self._pending_start = False
            return
        while True:
            await FallingEdge(self.sda)
            await ReadOnly()
            if self._scl_is_high():
                return

    async def _recv_byte(self, record=True):
        value = 0
        for bit in range(7, -1, -1):
            await RisingEdge(self.scl)
            await ReadOnly()
            if self._sda_is_high():
                value |= 1 << bit
        if record:
            self.observed_tokens.append(value)
        return value

    def handle_start(self):
        self._first_write = True
        self._read_buf = []

    async def handle_write(self, data):
        self.seen = True
        if self._first_write:
            self.reg_ptr = data
            self._first_write = False
        else:
            self.writes += 1
            self.handle_reg_write(self.reg_ptr, data)
            self.reg_ptr = (self.reg_ptr + 1) & 0xFF

    async def handle_read(self):
        self.seen = True
        if not self._read_buf:
            self._read_buf = list(self.make_read_response(self.reg_ptr))
        data = self._read_buf.pop(0) if self._read_buf else 0
        if not self._read_buf:
            self.reg_ptr = (self.reg_ptr + 1) & 0xFF
        self.reads += 1
        return data

    def handle_stop(self):
        self.transactions += 1
        self._first_write = True
        self._read_buf = []

    def handle_reg_write(self, reg, data):
        pass

    def make_read_response(self, reg):
        return [0]

    def is_data_write_reg(self, reg):
        return False

    async def _send_ack(self):
        await FallingEdge(self.scl)
        self._set_sda(0)
        await RisingEdge(self.scl)
        await FallingEdge(self.scl)
        self._set_sda(1)

    async def _send_byte(self, value):
        for bit in range(7, -1, -1):
            if self._scl_is_high():
                await FallingEdge(self.scl)
            self._set_sda((value >> bit) & 1)
            await RisingEdge(self.scl)
        await FallingEdge(self.scl)
        self._set_sda(1)
        await RisingEdge(self.scl)
        await ReadOnly()
        master_nack = self._sda_is_high()
        await FallingEdge(self.scl)
        return not master_nack

    async def _send_read_response(self, reg):
        response = list(self.make_read_response(reg))
        byte_index = 0
        while True:
            byte = response[byte_index] if byte_index < len(response) else 0x00
            byte_index += 1
            if not await self._send_byte(byte):
                return

    async def _run(self):
        """Handle write-reg/read-data and write-reg/write-data transactions."""

        self._set_sda(1)
        while True:
            await self._wait_start()
            self.handle_start()

            addr_rw = await self._recv_byte()
            addr = (addr_rw >> 1) & 0x7F
            read = bool(addr_rw & 1)
            if addr != self.addr:
                continue

            self.seen = True
            await self._send_ack()

            if read:
                await self._send_read_response(self.reg_ptr)
                self.transactions += 1
                continue

            reg = await self._recv_byte(record=False)
            await self.handle_write(reg)
            await self._send_ack()

            if self.is_data_write_reg(reg):
                data = await self._recv_byte(record=False)
                await self.handle_write(data)
                await self._send_ack()
                self.transactions += 1
                continue

            await self._wait_start()
            self.handle_start()
            addr_rw = await self._recv_byte()
            read_addr = (addr_rw >> 1) & 0x7F
            if read_addr != self.addr or not (addr_rw & 1):
                raise AssertionError(
                    f"unexpected repeated-start address 0x{addr_rw:02x} for device 0x{self.addr:02x}"
                )
            await self._send_ack()
            await self._send_read_response(reg)
            self.transactions += 1


class PassiveI2CAddressMonitor:
    """Non-driving monitor used to debug what the chip puts on the sensor pads.

    On timeout, the first decoded address bytes help distinguish pad activity
    problems from missing/incorrect sensor responses. Expected early bytes are
    usually 0x32 for ACC_ADDR write and 0xc8 for PPG_ADDR write.
    """

    def __init__(self, dut):
        self.dut = dut
        self.addr_bytes = []

    def _scl_is_high(self):
        return str(self.dut.sensor_scl_sample.value) == "1"

    def _sda_is_high(self):
        return str(self.dut.sensor_sda_sample.value) == "1"

    async def _wait_start(self):
        while True:
            await FallingEdge(self.dut.sensor_sda_sample)
            await ReadOnly()
            if self._scl_is_high():
                return

    async def _recv_byte(self):
        value = 0
        for bit in range(7, -1, -1):
            await RisingEdge(self.dut.sensor_scl_sample)
            await ReadOnly()
            if self._sda_is_high():
                value |= 1 << bit
        return value

    async def run(self):
        while True:
            await self._wait_start()
            self.addr_bytes.append(await self._recv_byte())


class Lis2dw12Device(RegisterSensorDevice):
    """LIS2DW12-like register behavior backed by accelerometer.py samples."""

    def __init__(self, *args, samples, **kwargs):
        self.samples = samples
        self.index = 0
        self.ctrl_writes = 0
        self.range_writes = 0
        self.sample_reads = 0
        self.last_sample = None
        super().__init__(*args, addr=ACC_ADDR, **kwargs)

    def handle_reg_write(self, reg, data):
        if reg == ACC_REG_CTRL1:
            self.ctrl_writes += 1
        elif reg == ACC_REG_RANGE:
            self.range_writes += 1

    def is_data_write_reg(self, reg):
        return reg in (ACC_REG_CTRL1, ACC_REG_RANGE)

    def make_read_response(self, reg):
        # STATUS reports data-ready. OUT_X_L returns XL/XH/YL/YH/ZL/ZH, matching
        # the existing SV sensor model's left-justified 14-bit sample format.
        if reg == ACC_REG_STATUS:
            return [0x01]
        if reg == ACC_REG_OUT_X_L:
            if self.index >= len(self.samples):
                self.index = 0
            sample = self.samples[self.index]
            self.index += 1
            self.sample_reads += 1
            self.last_sample = tuple(int(v) for v in sample)
            ax = (int(sample[0]) << 2) & 0xFFFF
            ay = (int(sample[1]) << 2) & 0xFFFF
            az = (int(sample[2]) << 2) & 0xFFFF
            return [ax & 0xFF, ax >> 8, ay & 0xFF, ay >> 8, az & 0xFF, az >> 8]
        return [0x00]


class Adpd144riDevice(RegisterSensorDevice):
    """ADPD144RI-like register behavior backed by ppg.py red-channel samples."""

    def __init__(self, *args, samples, **kwargs):
        self.samples = samples
        self.index = 0
        self.fifo_en_writes = 0
        self.fifo_reads = 0
        self._last_sample = 0
        self.last_sample = 0
        super().__init__(*args, addr=PPG_ADDR, **kwargs)

    def handle_reg_write(self, reg, data):
        if reg == PPG_REG_FIFO_ACCESS_ENA:
            self.fifo_en_writes += 1

    def is_data_write_reg(self, reg):
        return reg == PPG_REG_FIFO_ACCESS_ENA

    def _next_fifo_byte(self, byte_index):
        if byte_index % 2 == 0:
            if self.index >= len(self.samples):
                self.index = 0
            sample = int(self.samples[self.index]) & 0x3FFF
            self.index += 1
            self._last_sample = sample
            self.last_sample = sample
            return sample & 0xFF
        return (self._last_sample >> 8) & 0xFF

    def make_read_response(self, reg):
        # The FIFO path streams 16-bit little-endian words from the generated
        # PPG red-channel counts, matching what ppg_fifo_reader consumes.
        if reg == PPG_REG_STATUS:
            return [0x00, 0x10]
        if reg == PPG_REG_FIFO_THRESH:
            return [0x00, 0x02]
        if reg == PPG_REG_FIFO_ACCESS:
            self.fifo_reads += 1
            return [self._next_fifo_byte(i) for i in range(16)]
        return [0x00]


@cocotb.test()
async def test_chip_top_i2c_pads_reach_cocotbext_sensor_models(dut):
    """Drive chip_top sensor pads and require both sensor models to be reached.

    The DUT drives SCL/SDA through the real pad-level path. This test only
    supplies external open-drain sensor responses; it does not poke internal
    sim bus signals or force feature outputs.
    """

    log = dut._log
    accel_samples, ppg_samples = _build_sensor_model_streams()
    await _startup(dut)

    accel = Lis2dw12Device(
        sda=dut.sensor_sda_sample,
        sda_o=dut.accel_sda_o,
        scl=dut.sensor_scl_sample,
        scl_o=dut.accel_scl_o,
        samples=accel_samples,
    )
    ppg = Adpd144riDevice(
        sda=dut.sensor_sda_sample,
        sda_o=dut.ppg_sda_o,
        scl=dut.sensor_scl_sample,
        scl_o=dut.ppg_scl_o,
        samples=ppg_samples,
    )
    accel.log.setLevel(logging.WARNING)
    ppg.log.setLevel(logging.WARNING)

    # This monitor never drives SDA. It is only here to make failures actionable
    # by showing which 8-bit address phases were visible on the physical pads.
    addr_monitor = PassiveI2CAddressMonitor(dut)
    cocotb.start_soon(addr_monitor.run())

    debug_handles = _collect_debug_handles(dut)
    verbose = os.getenv("I2C_PAD_VERBOSE", "0") == "1"
    pulse_monitors = {
        "acc_rsp_valid": PulseMonitor(
            debug_handles["acc_rsp_valid"],
            lambda: (
                _format_signal(debug_handles["acc_rsp_data"], 8),
                _format_signal(debug_handles["acc_rsp_done"]),
                _format_signal(debug_handles["acc_rsp_err"]),
            ),
        ),
        "accel_valid": PulseMonitor(
            debug_handles["accel_valid"],
            lambda: (
                _format_signal(debug_handles["ax"], 16),
                _format_signal(debug_handles["ay"], 16),
                _format_signal(debug_handles["az"], 16),
            ),
        ),
        "ppg_rsp_valid": PulseMonitor(
            debug_handles["ppg_rsp_valid"],
            lambda: (
                _format_signal(debug_handles["ppg_rsp_data"], 8),
                _format_signal(debug_handles["ppg_rsp_last"]),
                _format_signal(debug_handles["ppg_rsp_err"]),
            ),
        ),
        "ppg_sample_valid": PulseMonitor(
            debug_handles["ppg_sample_valid"],
            lambda: (
                _format_signal(debug_handles["ppg_sample"], 16),
                _format_signal(debug_handles["ppg_sample_time"], 32),
            ),
        ),
        "feat_valid": PulseMonitor(debug_handles["feat_valid"]),
    }
    for monitor in pulse_monitors.values():
        cocotb.start_soon(monitor.run())

    def pulse_counts():
        return {name: monitor.count for name, monitor in pulse_monitors.items()}

    saw_scl_toggle = False
    last_scl = str(dut.sensor_scl_sample.value)
    max_cycles = int(os.getenv("I2C_PAD_MAX_CYCLES", "250000"))
    post_observe_cycles = int(os.getenv("I2C_PAD_POST_OBSERVE_CYCLES", "10000"))
    reached_models_cycle = None
    sample_clock = debug_handles["core_clk"] if debug_handles["core_clk"] is not None else dut.clk_drv

    for cycle in range(max_cycles):
        await RisingEdge(sample_clock)
        await ReadOnly()
        scl = str(dut.sensor_scl_sample.value)
        saw_scl_toggle = saw_scl_toggle or (scl != last_scl)
        last_scl = scl

        if verbose and cycle and cycle % DEBUG_SNAPSHOT_PERIOD_CYCLES == 0:
            _log_debug_summary(log, dut, accel, ppg, addr_monitor, debug_handles, pulse_counts())

        if accel.sample_reads > 0 and ppg.fifo_reads > 0 and reached_models_cycle is None:
            reached_models_cycle = cycle
            log.info(
                "pad I2C reached both models at cycle %d: accel_samples=%d ppg_fifo_reads=%d ppg_samples=%d",
                cycle,
                accel.sample_reads,
                ppg.fifo_reads,
                ppg.index,
            )

        readers_consumed = (
            pulse_monitors["accel_valid"].count > 0 and pulse_monitors["ppg_sample_valid"].count > 0
        )
        if reached_models_cycle is not None and readers_consumed and cycle - reached_models_cycle >= post_observe_cycles:
            break
    else:
        _log_debug_summary(log, dut, accel, ppg, addr_monitor, debug_handles, pulse_counts())
        # The extra counters separate "no pad clocks", "wrong address",
        # "init never completed", and "data FIFO never reached" failures.
        raise AssertionError(
            "timed out waiting for cocotbext I2C sensor traffic; "
            f"scl_toggle={saw_scl_toggle}, "
            f"accel_seen={accel.seen}, accel_samples={accel.sample_reads}, "
            f"accel_ctrl_writes={accel.ctrl_writes}, accel_range_writes={accel.range_writes}, "
            f"ppg_seen={ppg.seen}, ppg_fifo_en_writes={ppg.fifo_en_writes}, "
            f"ppg_fifo_reads={ppg.fifo_reads}, "
            f"accel_tokens={accel.observed_tokens[:16]}, "
            f"ppg_tokens={ppg.observed_tokens[:16]}, "
            f"addr_bytes={[hex(b) for b in addr_monitor.addr_bytes[:16]]}"
        )

    _log_debug_summary(log, dut, accel, ppg, addr_monitor, debug_handles, pulse_counts())
    log.info(
        "internal pulse samples: acc_rsp=%s accel_valid=%s ppg_rsp=%s ppg_sample=%s",
        pulse_monitors["acc_rsp_valid"].samples[:12],
        pulse_monitors["accel_valid"].samples[:4],
        pulse_monitors["ppg_rsp_valid"].samples[:20],
        pulse_monitors["ppg_sample_valid"].samples[:8],
    )

    assert saw_scl_toggle, "sensor SCL pad did not toggle"
    assert accel.ctrl_writes > 0, "accelerometer CTRL1 init write was not observed"
    assert accel.range_writes > 0, "accelerometer range init write was not observed"
    assert accel.sample_reads > 0, "accelerometer data was not read through pads"
    assert ppg.fifo_en_writes > 0, "PPG FIFO access enable write was not observed"
    assert ppg.fifo_reads > 0, "PPG FIFO data was not read through pads"
    assert pulse_monitors["accel_valid"].count > 0, "accelerometer reader did not emit accel_valid_w"
    assert pulse_monitors["ppg_sample_valid"].count > 0, "PPG FIFO reader did not emit ppg_sample_valid_w"
