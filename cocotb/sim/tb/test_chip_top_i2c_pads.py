async def _startup(dut):
    """Put chip_top in sensor debug mode and release reset.

    TEST_MODE_MSSD enables the sensor/feature path used by the existing pad
    bridge checks. The bidir drive signals are released except for SDA, where
    this test's I2C devices may pull the line low through open-drain controls.
    """

    dut.input_drv.value = TEST_MODE_MSSD
    dut.bidir_drv.value = 0
    dut.bidir_oe.value = 0
    dut.sensor_sda_drive_low.value = 0
    dut.accel_sda_o.value = 1
    dut.ppg_sda_o.value = 1
    dut.accel_scl_o.value = 1
    dut.ppg_scl_o.value = 1
    dut.rst_n_drv.value = 0
    cocotb.start_soon(Clock(dut.clk_drv, 40, "ns").start())
    await Timer(400, "ns")
    dut.rst_n_drv.value = 1


def _build_sensor_model_streams():
    """Generate deterministic digital streams with the project sensor models.

    The production model scripts normally write CSV files for SV simulations.
    Here we call the same processing functions directly and keep the returned
    arrays in memory, avoiding PhysioNet/network access during the cocotb run.
    """

    sample_count = int(os.getenv("I2C_PAD_SENSOR_MODEL_SAMPLES", "512"))
    rng_seed = int(os.getenv("I2C_PAD_SENSOR_MODEL_SEED", "7"))
    np.random.seed(rng_seed)

    accel_t = np.arange(sample_count, dtype=float) / 25.0
    raw_g = np.column_stack(
        [
            0.020 * np.sin(2 * np.pi * 0.25 * accel_t),
            0.015 * np.cos(2 * np.pi * 0.18 * accel_t),
            1.000 + 0.010 * np.sin(2 * np.pi * 0.11 * accel_t),
        ]
    )

    bpm_t = np.arange(0.0, max(12.0, sample_count / 25.0 + 4.0), 1.0)
    bpm = 64.0 + 3.0 * np.sin(2 * np.pi * bpm_t / 20.0)

    with tempfile.TemporaryDirectory(prefix="sensor_model_i2c_") as tmp:
        tmp_path = Path(tmp)
        accel_model.PLOT_DIR = str(tmp_path / "plots")
        ppg_model.PLOT_DIR = str(tmp_path / "plots")
        accel_counts = accel_model.process_accelerometer(raw_g, tmp_path)
        red_counts, _ir_counts = ppg_model.process_ppg(bpm_t, bpm, tmp_path)

    return accel_counts.astype(np.int16), red_counts.astype(np.uint16)


def _get_optional_handle(dut, path):
    handle = dut
    for name in path.split("."):
        try:
            handle = getattr(handle, name)
        except (AttributeError, ValueError):
            return None
    return handle


def _value_to_int(value):
    try:
        return value.to_unsigned()
    except (AttributeError, ValueError):
        try:
            return value.to_signed()
        except (AttributeError, ValueError):
            return None


def _format_signal(handle, width_hint=None):
    if handle is None:
        return "n/a"
    value = handle.value
    intval = _value_to_int(value)
    if intval is None:
        return str(value)
    if width_hint is not None:
        mask = (1 << width_hint) - 1
        return f"0x{intval & mask:0{max(1, (width_hint + 3) // 4)}x}"
    return str(intval)


